def days(value)
  return nil if value == '-'
  parts = value.split('-').map(&:to_i)
  { 'min' => parts.first, 'max' => parts.last }
end

def household_profile(name, category)
  highly_perishable = %w[菠菜 小白菜 上海青 生菜 油麦菜 空心菜 韭菜 香菜 茼蒿 苋菜 菜心 香菇 平菇 金针菇 口蘑 海鲜菇 木耳 银耳 草莓 树莓 无花果 猪肉馅 牛肉馅 猪肝 鸡肝 奶油蛋糕 慕斯蛋糕 泡芙 提拉米苏]
  durable = %w[土豆 红薯 紫薯 山药 芋头 洋葱 生姜 大蒜 南瓜 冬瓜 苹果 柚子 柠檬 石榴 椰子 大米 糙米 小米 燕麦 面粉 玉米面 黄豆 绿豆 红豆 黑豆 花生 干鹰嘴豆 干扁豆]
  if category == '水产' || highly_perishable.include?(name)
    { 'level' => 'high', 'remaining_life_factor' => 0.60, 'fresh_stage_share' => 0.35 }
  elsif durable.include?(name) || category == '谷豆'
    { 'level' => 'low', 'remaining_life_factor' => 0.90, 'fresh_stage_share' => 0.60 }
  elsif %w[肉蛋 乳制品 豆制品].include?(category)
    { 'level' => 'medium_high', 'remaining_life_factor' => 0.72, 'fresh_stage_share' => 0.42 }
  else
    { 'level' => 'medium', 'remaining_life_factor' => 0.75, 'fresh_stage_share' => 0.45 }
  end
end

def category_tag_for(name, category)
  return '蛋类' if category == '肉蛋' && name.include?('蛋')
  return '肉类' if category == '肉蛋'
  {
    '蔬菜' => '蔬菜', '菌菇' => '菌菇', '水果' => '水果', '水产' => '海鲜',
    '谷豆' => '谷物杂粮', '豆制品' => '豆制品', '乳制品' => '乳制品', '烘焙' => '烘焙'
  }.fetch(category, '其他')
end

def freshness_standard(range, profile, storage)
  return nil unless range
  factor = storage == 'frozen' ? [profile['remaining_life_factor'] + 0.15, 0.95].min : profile['remaining_life_factor']
  fresh_share = storage == 'frozen' ? 0.60 : profile['fresh_stage_share']
  household_max = [1, (range['max'] * factor).ceil].max
  fresh_max = [(household_max * fresh_share).floor, household_max - 1].min
  {
    'fresh' => { 'label' => '新鲜', 'max_days' => fresh_max },
    'consume_soon' => { 'label' => '尽快食用', 'min_days' => fresh_max + 1, 'max_days' => household_max },
    'not_recommended' => { 'label' => '不宜食用', 'min_days' => household_max + 1 },
    'reference_max_days' => range['max'],
    'household_max_days' => household_max
  }
end

